from __future__ import annotations

"""Safe, data-only material packs for the Qt user interface.

Material packs deliberately are *not* Qt stylesheets.  A package may contain a
strict JSON manifest and, optionally, one raster background.  All Qt CSS is
generated by this module from validated colour tokens, so importing a pack can
never introduce a script, an arbitrary URL, or a QSS selector.
"""

from dataclasses import dataclass
import json
import os
from pathlib import Path, PurePosixPath
import re
import stat
import tempfile
from typing import Literal
import unicodedata
import zipfile

from pydantic import BaseModel, ConfigDict, Field, ValidationError, field_validator, model_validator


PACK_EXTENSION = ".aifopack"
MANIFEST_NAME = "manifest.json"
PACK_FORMAT_VERSION = 1
MAX_ARCHIVE_BYTES = 12 * 1024 * 1024
MAX_MANIFEST_BYTES = 64 * 1024
MAX_BACKGROUND_BYTES = 10 * 1024 * 1024
MAX_TOTAL_UNPACKED_BYTES = 11 * 1024 * 1024
MAX_ARCHIVE_ENTRIES = 3
MAX_COMPRESSION_RATIO = 100.0
MAX_IMAGE_DIMENSION = 8192
MAX_IMAGE_PIXELS = 32_000_000

_PACK_ID_RE = re.compile(r"^[a-z0-9][a-z0-9_-]{0,63}$")
_VERSION_RE = re.compile(r"^[0-9]+(?:\.[0-9]+){0,3}$")
_COLOR_RE = re.compile(r"^#[0-9A-Fa-f]{6}$")
_BACKGROUND_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9_. -]{0,127}\.(?:png|jpe?g|webp)$", re.I)
_WINDOWS_RESERVED = {
    "con", "prn", "aux", "nul", *(f"com{i}" for i in range(1, 10)),
    *(f"lpt{i}" for i in range(1, 10)),
}


def _rgba(value: str) -> tuple[float, float, float, float]:
    raw = value.removeprefix("#")
    alpha = int(raw[6:8], 16) / 255 if len(raw) == 8 else 1.0
    return tuple(int(raw[index:index + 2], 16) / 255 for index in (0, 2, 4)) + (alpha,)


def _blend(value: str, background: tuple[float, float, float]) -> tuple[float, float, float]:
    red, green, blue, alpha = _rgba(value)
    return tuple(alpha * foreground + (1 - alpha) * behind for foreground, behind in zip((red, green, blue), background))


def _luminance(rgb: tuple[float, float, float]) -> float:
    channels = tuple(value / 12.92 if value <= 0.04045 else ((value + 0.055) / 1.055) ** 2.4 for value in rgb)
    return 0.2126 * channels[0] + 0.7152 * channels[1] + 0.0722 * channels[2]


def _contrast(foreground: str, background: tuple[float, float, float]) -> float:
    foreground_luminance = _luminance(_blend(foreground, background))
    background_luminance = _luminance(background)
    lighter, darker = max(foreground_luminance, background_luminance), min(foreground_luminance, background_luminance)
    return (lighter + 0.05) / (darker + 0.05)


class MaterialPackError(RuntimeError):
    """Base error suitable for displaying in a settings dialog."""


class UnsafeMaterialPack(MaterialPackError):
    """The package failed a security or resource-limit check."""


class MaterialPackNotFound(MaterialPackError):
    """The requested material pack does not exist."""


class ColorTokens(BaseModel):
    """The only values a material pack may feed into generated QSS."""

    model_config = ConfigDict(extra="forbid", strict=True, frozen=True)

    window: str
    panel: str
    elevated: str
    input: str
    text: str
    muted_text: str
    accent: str
    accent_hover: str
    accent_pressed: str
    border: str
    selection_text: str
    success: str
    warning: str
    danger: str

    @field_validator("*")
    @classmethod
    def validate_colour(cls, value: str) -> str:
        if not _COLOR_RE.fullmatch(value):
            raise ValueError("颜色必须使用 #RRGGBB（不接受透明通道）")
        return value.upper()


class MaterialManifest(BaseModel):
    """Strict, versioned and data-only on-disk package manifest."""

    model_config = ConfigDict(extra="forbid", strict=True, frozen=True)

    format_version: Literal[1] = PACK_FORMAT_VERSION
    id: str = Field(min_length=1, max_length=64)
    name: str = Field(min_length=1, max_length=80)
    version: str = Field(default="1.0", min_length=1, max_length=24)
    author: str = Field(default="", max_length=80)
    description: str = Field(default="", max_length=500)
    colors: ColorTokens
    background: str | None = None
    background_mode: Literal["cover", "tile", "center"] = "cover"

    @field_validator("id")
    @classmethod
    def valid_id(cls, value: str) -> str:
        if not _PACK_ID_RE.fullmatch(value):
            raise ValueError("材质包 ID 只能包含小写字母、数字、下划线和连字符")
        if value in {".", ".."}:
            raise ValueError("材质包 ID 无效")
        return value

    @field_validator("name")
    @classmethod
    def nonempty_safe_name(cls, value: str) -> str:
        value = value.strip()
        if not value:
            raise ValueError("材质包名称不能为空")
        if any(unicodedata.category(char) in {"Cc", "Cf", "Cs"} for char in value) or any(char in "<>&" for char in value):
            raise ValueError("材质包名称必须是安全的单行纯文本")
        return value

    @field_validator("author", "description")
    @classmethod
    def safe_metadata(cls, value: str) -> str:
        value = value.strip()
        if any(unicodedata.category(char) in {"Cc", "Cf", "Cs"} for char in value):
            raise ValueError("文本包含控制字符")
        return value

    @field_validator("version")
    @classmethod
    def valid_version(cls, value: str) -> str:
        if not _VERSION_RE.fullmatch(value):
            raise ValueError("版本号格式无效")
        return value

    @field_validator("background")
    @classmethod
    def valid_background_name(cls, value: str | None) -> str | None:
        if value is None:
            return None
        if not _BACKGROUND_RE.fullmatch(value):
            raise ValueError("背景必须是包根目录下的 PNG、JPG 或 WebP 文件")
        _validate_member_name(value)
        return value

    @model_validator(mode="after")
    def readable_colours(self) -> "MaterialManifest":
        colors = self.colors
        if _rgba(colors.window)[3] < 0.95:
            raise ValueError("窗口背景不能高度透明")
        white = (1.0, 1.0, 1.0)
        window = _blend(colors.window, white)
        panel = _blend(colors.panel, window)
        elevated = _blend(colors.elevated, panel)
        input_background = _blend(colors.input, panel)
        text_backgrounds = (window, panel, elevated, input_background)
        if min(_contrast(colors.text, background) for background in text_backgrounds) < 4.5:
            raise ValueError("正文颜色与界面背景的对比度不足")
        if min(_contrast(colors.muted_text, background) for background in (window, panel)) < 3.0:
            raise ValueError("辅助文字颜色与背景的对比度不足")
        if min(_contrast(colors.selection_text, _blend(accent, panel)) for accent in (colors.accent, colors.accent_hover, colors.accent_pressed)) < 4.5:
            raise ValueError("按钮/选择文字与强调色的对比度不足")
        if min(_contrast(colors.border, background) for background in (window, panel, input_background)) < 2.5:
            raise ValueError("边框颜色与背景的对比度不足")
        for status in (colors.success, colors.warning, colors.danger):
            if min(_contrast(status, background) for background in (window, panel)) < 3.0:
                raise ValueError("状态颜色与背景的对比度不足")
        return self


class MaterialPack(BaseModel):
    """A resolved built-in or user-installed material pack."""

    model_config = ConfigDict(extra="forbid", strict=True, frozen=True)

    manifest: MaterialManifest
    source: Literal["builtin", "custom"]
    directory: Path | None = None
    background_path: Path | None = None

    @property
    def id(self) -> str:
        return self.manifest.id

    @property
    def name(self) -> str:
        return self.manifest.name


@dataclass(frozen=True)
class AppliedMaterial:
    pack: MaterialPack
    stylesheet: str

    @property
    def id(self) -> str:
        return self.pack.id


