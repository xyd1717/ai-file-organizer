    c = pack.manifest.colors
    background_rule = ""
    if pack.background_path is not None:
        path = pack.background_path.resolve()
        if pack.directory is None or path.parent != pack.directory.resolve() or _is_link_like(path):
            raise UnsafeMaterialPack("背景文件路径越界")
        # pathlib.as_uri percent-encodes QSS punctuation; the manifest never
        # controls selectors or property names.
